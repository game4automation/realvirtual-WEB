// Node-only generator: never import this module from the browser.
import { createHash } from 'node:crypto';
import { CLASS_RANK, type McpToolClass } from './rv-mcp-tool-class';

export function renderCommandClassAllowlist(table: ReadonlyMap<string, McpToolClass>, macroReplayClass: McpToolClass): string {
  const rows = [...table.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const hash = createHash('sha256').update(rows.map(([id, cls]) => `${id}=${cls}`).join('\n') + `\nreplay=${macroReplayClass}`).digest('hex');
  return [
    '// realvirtual CONNECT — Standalone Signal Gateway',
    '// Copyright(c) 2026 realvirtual GmbH',
    '//',
    '// GENERATED by realvirtual-WebViewer~/tests/mcp-tool-class-convention.node.test.ts',
    '// (npm run gen:mcp-docs). Do not edit by hand — change the class in',
    '// src/plugins/mcp-bridge/rv-mcp-tool-class.ts and regenerate.',
    '',
    'namespace realvirtual.Connect.Api.Mcp;',
    '',
    '/// <summary>Command classes derived from the WebViewer registry (plan-2007 F6).</summary>',
    'public static class McpCommandClassAllowlist',
    '{',
    '    public const string Unclassified = "unclassified";',
    `    public const string MacroReplayClass = "${macroReplayClass}";`,
    `    public const string Hash = "${hash}";`,
    '',
    '    public static readonly IReadOnlyDictionary<string, string> Classes = new Dictionary<string, string>(StringComparer.Ordinal)',
    '    {',
    ...rows.map(([id, cls]) => `        [${JSON.stringify(id)}] = "${cls}",`),
    '    };',
    '',
    `    public static readonly IReadOnlyList<string> Rank = new[] { ${CLASS_RANK.map((cls) => `"${cls}"`).join(', ')} };`,
    '',
    '    public static string ClassOf(string id) => Classes.TryGetValue(id, out var c) ? c : "edit";',
    '',
    '    public static bool IsKnown(string id) => Classes.ContainsKey(id);',
    '}',
    '',
  ].join('\r\n');
}
