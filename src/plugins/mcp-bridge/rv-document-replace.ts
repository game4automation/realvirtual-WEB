// ─── Contract ───────────────────────────────────────────────────────────

export type ReplaceFailureReason =
  | 'revision-conflict'
  | 'local-changes'
  | 'project-mismatch'
  | 'read-only'
  | 'invalid-glb'
  | 'not-found'
  | 'foreign-origin'
  | 'reload-failed-restored'
  | 'restore-failed'
  | 'duplicate-operation'
  | 'write-failed';

export interface ReplaceArgs {
  /** Generated by the producer (UUID) — the idempotency key. */
  operationId: string;
  /** From the pull; must be the active project. */
  projectId: string;
  documentId: string;
  /** Same-origin staging URL (staged by CONNECT). Exactly one of `stagingUrl` / `bytes`. */
  stagingUrl?: string;
  /**
   * The new GLB bytes, produced in this page (plan-764 apply). Skips the origin
   * check and the fetch; the full parse and every other step stay.
   */
  bytes?: Uint8Array;
  /** The pull's revision, or `'any'` for an explicit overwrite (skips ONLY the revision conflict). */
  expectedRevision: string;
}

export type ReplaceResult =
  | {
    ok: true;
    operationId: string;
    revision: string;
    reloaded: 'open-document' | 'placements' | 'none';
    /**
     * LOP #180: why a reload that was due did not run. `document-switched` —
     * another document was opened while the replace ran; the file is written,
     * the other document (and its draft) untouched. Open the document to see it.
     */
    reloadSkipped?: 'document-switched';
    placementsRebaked: number;
    /** Placements of the document that still show the previous bytes (host document not reloadable). */
    placementsStale?: number;
    detail?: string;
  }
  | {
    ok: false;
    operationId: string;
    reason: ReplaceFailureReason;
    detail: string;
    /** The file's revision after a restore, when one was written. */
    revision?: string;
  };

export interface ReplaceStatus {
  operationId: string;
  status: 'pending' | 'done' | 'unknown-operation';
  /** The bridge session asked. */
  sessionId: string;
  result?: ReplaceResult;
  detail?: string;
}

/** The open document, as a replace needs it. */
export interface ReplaceDocumentHandle {
  /** Unsaved work in the op log (a pending draft write of it is covered by `hasDraft`). */
  isDirty(): boolean;
  /** The replace lock on the op queue — null when it is held already. */
  lock(): Promise<DocumentLockToken | null>;
  unlock(token: DocumentLockToken): void;
  /**
   * Reload from the file, camera kept, draft dropped, undo history empty.
   * Answers `'document-switched'` WITHOUT reloading (and without touching any
   * draft) when the open document is no longer the one the lock was taken on
   * (LOP #180); anything else means it reloaded.
   */
  reload(token: DocumentLockToken): Promise<void | 'reloaded' | 'document-switched'>;
}

export interface ReplaceDocumentRow { id: string; path: string; name: string }

/** Everything the replace needs from the running viewer — see {@link createViewerReplaceDeps}. */
export interface ReplaceDeps {
  /** The bridge session the call arrived on. */
  sessionId(): string;
  activeProjectId(): string | null;
  backend(): ProjectBackend | null;
  findDocument(documentId: string): ReplaceDocumentRow | null;
  /** The page origin staging URLs must share. */
  pageOrigin(): string;
  fetchStaged(url: string): Promise<Uint8Array>;
  /** Full in-memory parse (Draco included); throws on anything the viewer could not load. */
  validateGlb(bytes: Uint8Array): Promise<void>;
  hasDraft(documentId: string): Promise<boolean>;
  /** The asset editor holds this document — a reload under it is not supported. */
  editorHolds(documentId: string): boolean;
  /** The open document when it IS `documentId`, else null. */
  openTarget(documentId: string): ReplaceDocumentHandle | null;
  /** The open document whatever it is (a host of placements), else null. */
  openHost(): ReplaceDocumentHandle | null;
  /** Drop every cached decode / bake / byte of the document; returns the live placements of it. */
  invalidate(doc: ReplaceDocumentRow): Promise<number>;
  /** `placements.progress.missing` of the open document. */
  placementsMissing(): number;
  /** Resolves once the open document and its placements have settled. */
  whenSettled(): Promise<void>;
  reportFailure(doc: { id: string; name: string }, result: Extract<ReplaceResult, { ok: false }>): void;
  clearFailure(documentId: string): void;
  /**
   * After a successful replace: the rest of the one post-save step (plan-777
   * F6) — `finishDocumentSave` without its announce, which `invalidate` made
   * early. `loaded` = the replaced document is the one on screen, so its
   * thumbnail is rendered again (plan-776 F6); otherwise the pointer is removed
   * and the sidecar deleted. Then the background rescan. Optional — a test
   * double without it simply leaves thumbnails and the listing alone.
   */
  finishSave?(doc: ReplaceDocumentRow, loaded: boolean): Promise<void>;
}

// ─── Operation register ─────────────────────────────────────────────────

/** The Problems-panel code (and id prefix) of a refused or failed replace. */
export const REPLACE_PROBLEM_CODE = 'document-replace-failed';

/** How many finished operations are remembered per page. */
export const OPERATION_HISTORY = 32;

interface OperationRecord {
  operationId: string;
  sessionId: string;
  projectId: string;
  documentId: string;
  state: 'pending' | 'done';
  promise: Promise<ReplaceResult>;
  result?: ReplaceResult;
}

const _operations = new Map<string, OperationRecord>();

/** Test seam — forget every operation. */
export function resetReplaceOperationsForTests(): void {
  _operations.clear();
}

function prune(): void {
  if (_operations.size <= OPERATION_HISTORY) return;
  for (const [id, rec] of _operations) {
    if (_operations.size <= OPERATION_HISTORY) break;
    if (rec.state === 'done') _operations.delete(id);
  }
}

/**
 * Replace a document — the whole 1–8 sequence (module header).
 *
 * Synchronous up to the registration: a second call with the same id that
 * arrives while the first one still decodes gets the SAME promise.
 */
export function replaceDocument(
  args: ReplaceArgs,
  depsOrFactory: ReplaceDeps | (() => Promise<ReplaceDeps>),
  opts: { sessionId?: string } = {},
): Promise<ReplaceResult> {
  const operationId = String(args.operationId ?? '').trim();
  const known = _operations.get(operationId);
  if (known) {
    if (known.documentId !== args.documentId || known.projectId !== args.projectId) {
      return Promise.resolve({
        ok: false,
        operationId,
        reason: 'duplicate-operation',
        detail: `Operation ${operationId} was already used for another document/project — `
          + 'every push needs a fresh operationId. Nothing was written.',
      });
    }
    return known.promise;
  }
  const record: OperationRecord = {
    operationId,
    sessionId: opts.sessionId
      ?? (typeof depsOrFactory === 'function' ? 'local' : depsOrFactory.sessionId()),
    projectId: args.projectId,
    documentId: args.documentId,
    state: 'pending',
    promise: Promise.resolve(null as unknown as ReplaceResult),
  };
  _operations.set(operationId, record);
  // The deps are built AFTER the registration — building them awaits imports.
  const deps = typeof depsOrFactory === 'function' ? depsOrFactory() : Promise.resolve(depsOrFactory);
  record.promise = deps.then((d) => runReplace({ ...args, operationId }, d))
    .catch((e): ReplaceResult => ({
      // A defect after the registration. Nothing below lets a write go
      // unreported, so this is answered as the failure it is — never as success.
      ok: false, operationId, reason: 'write-failed', detail: `Unexpected failure: ${messageOf(e)}`,
    }))
    .then((result) => {
      record.state = 'done';
      record.result = result;
      prune();
      return result;
    });
  prune();
  return record.promise;
}

/**
 * The outcome of an operation, for the bridge session that asks.
 *
 * `unknown-operation` is NOT "did not happen": the id may have run on another
 * session (a reload, another tab, a reconnect) whose register this page does
 * not have. The producer resolves it only by pulling again and comparing revisions.
 */
export function replaceStatus(operationId: string, sessionId: string): ReplaceStatus {
  const id = String(operationId ?? '').trim();
  const rec = _operations.get(id);
  const unknown = (detail: string): ReplaceStatus => ({ operationId: id, status: 'unknown-operation', sessionId, detail });
  if (!rec) {
    return unknown('This bridge session does not know the operation. That does NOT mean it did not happen '
      + '(it may have run before a reload / reconnect or in another tab). Pull the document again and compare '
      + 'its revision with the one the push would have produced.');
  }
  if (rec.sessionId !== sessionId) {
    return unknown(`The operation ran on another bridge session (${rec.sessionId}); its outcome is not reported `
      + 'across sessions. Pull the document again and compare revisions.');
  }
  return rec.state === 'pending'
    ? { operationId: id, status: 'pending', sessionId }
    : { operationId: id, status: 'done', sessionId, result: rec.result };
}

// ─── The sequence ───────────────────────────────────────────────────────

function messageOf(e: unknown): string {
  return e instanceof Error ? e.message : String(e);
}

function isRevisionConflict(e: unknown): boolean {
  return (e as { name?: string } | null)?.name === 'SceneRevisionConflictError';
}

async function runReplace(args: ReplaceArgs, deps: ReplaceDeps): Promise<ReplaceResult> {
  const operationId = args.operationId;
  let docForReport: { id: string; name: string } = { id: args.documentId, name: args.documentId };
  const fail = (reason: ReplaceFailureReason, detail: string, revision?: string): ReplaceResult => {
    const result: Extract<ReplaceResult, { ok: false }> = {
      ok: false, operationId, reason, detail, ...(revision ? { revision } : {}),
    };
    try { deps.reportFailure(docForReport, result); } catch { /* reporting never decides the outcome */ }
    return result;
  };

  // ── 2. project, document, origin ──
  const active = deps.activeProjectId();
  if (!active || active !== args.projectId) {
    return fail('project-mismatch', `The open project is ${active ? `"${active}"` : 'none'}, the document was `
      + `pulled from "${args.projectId}". Pull again from the project that is open.`);
  }
  const backend = deps.backend();
  const doc = deps.findDocument(args.documentId);
  if (!backend || !doc) {
    return fail('not-found', `No document "${args.documentId}" in the open project.`);
  }
  docForReport = { id: doc.id, name: doc.name || doc.path };
  if (!backend.writable) {
    return fail('read-only', `The project is read-only — "${doc.path}" cannot be replaced.`);
  }
  const inPage = args.bytes instanceof Uint8Array;
  if (inPage === (typeof args.stagingUrl === 'string' && args.stagingUrl !== '')) {
    return fail('not-found', 'A replace needs exactly one source: a staging URL or the bytes. Nothing was written.');
  }
  let staging: URL | null = null;
  if (!inPage) {
    try {
      staging = new URL(args.stagingUrl!, deps.pageOrigin() + '/');
    } catch {
      return fail('foreign-origin', `"${args.stagingUrl}" is not a URL.`);
    }
    if ((staging.protocol !== 'http:' && staging.protocol !== 'https:') || staging.origin !== deps.pageOrigin()) {
      return fail('foreign-origin', `The staging URL ${staging.origin} is not this viewer's origin `
        + `(${deps.pageOrigin()}). The live link needs the viewer served by CONNECT (same origin).`);
    }
  }

  // ── 3. a draft of the target, open or not ──
  if (await deps.hasDraft(doc.id)) {
    return fail('local-changes', `"${doc.name || doc.path}" has unsaved changes in realvirtual WEB (a draft). `
      + 'Save or discard them in the viewer first — WEB wins, the push wrote nothing.');
  }

  // ── 4. the open target: dirty, lock, dirty again ──
  if (deps.editorHolds(doc.id)) {
    return fail('local-changes', `"${doc.name || doc.path}" is open in the asset editor. Close the editor `
      + '(save or discard there), then push again. Nothing was written.');
  }
  const open = deps.openTarget(doc.id);
  let token: DocumentLockToken | null = null;
  if (open) {
    if (open.isDirty()) {
      return fail('local-changes', `"${doc.name || doc.path}" has unsaved changes in realvirtual WEB. Save or `
        + 'discard them first — WEB wins, the push wrote nothing.');
    }
    token = await open.lock();
    if (!token) {
      return fail('local-changes', `"${doc.name || doc.path}" is busy in realvirtual WEB (another push is `
        + 'replacing it). Nothing was written.');
    }
  }
  try {
    if (open && open.isDirty()) {
      return fail('local-changes', `"${doc.name || doc.path}" was changed in realvirtual WEB while the push `
        + 'waited for it. Nothing was written.');
    }

    // ── 5. fetch + full parse ──
    let bytes: Uint8Array;
    if (staging) {
      try {
        bytes = await deps.fetchStaged(staging.href);
      } catch (e) {
        return fail('not-found', `The staged upload could not be read: ${messageOf(e)}`);
      }
    } else {
      bytes = args.bytes!;
    }
    try {
      await deps.validateGlb(bytes);
    } catch (e) {
      return fail('invalid-glb', `The pushed file is not a loadable GLB: ${messageOf(e)}. Nothing was written.`);
    }
    // The project may have been switched while the bytes were parsed.
    if (deps.activeProjectId() !== args.projectId) {
      return fail('project-mismatch', 'The open project changed while the push was being checked. Nothing was written.');
    }

    // ── 6. keep the previous bytes, write with the precondition ──
    const ref = { path: doc.path, id: doc.id };
    let previous: { bytes: Uint8Array; revision: string } | null = null;
    try {
      const rec = await backend.readDocument(ref);
      if (rec) previous = { bytes: rec.bytes, revision: rec.revision };
    } catch { /* an unreadable previous file only means there is nothing to restore */ }
    let revision: string;
    try {
      ({ revision } = await backend.writeDocument(ref, bytes, {
        expectedRevision: args.expectedRevision === 'any' ? 'any' : args.expectedRevision,
      }));
    } catch (e) {
      if (isRevisionConflict(e)) {
        return fail('revision-conflict', `"${doc.path}" was changed in realvirtual WEB since the pull `
          + `(${messageOf(e)}). Pull again, or overwrite deliberately.`);
      }
      return fail('write-failed', `"${doc.path}" could not be written: ${messageOf(e)}. The file is unchanged.`);
    }

    // ── 7. caches + reload ──
    const missingBefore = deps.placementsMissing();
    // Mutated by `show()` — an object, so the type checker does not narrow the
    // fields to their initial values across the closure.
    const shown: {
      reloaded: 'open-document' | 'placements' | 'none';
      rebaked: number;
      stale: number;
      switched: boolean;
      host: ReplaceDocumentHandle | null;
      hostToken: DocumentLockToken | null;
    } = { reloaded: 'none', rebaked: 0, stale: 0, switched: false, host: null, hostToken: null };
    const show = async (): Promise<void> => {
      const affected = await deps.invalidate(doc);
      if (open && token) {
        shown.reloaded = 'open-document';
        shown.rebaked = affected;
        if (await open.reload(token) === 'document-switched') {
          // LOP #180: another document is open now — leave it (and its draft) alone.
          shown.reloaded = 'none';
          shown.rebaked = 0;
          shown.switched = true;
          return;
        }
        await deps.whenSettled();
        return;
      }
      if (affected === 0) return;
      shown.host ??= deps.openHost();
      if (shown.host && !shown.hostToken && !shown.host.isDirty() && !deps.editorHolds('')) {
        shown.hostToken = await shown.host.lock();
      }
      if (shown.host && shown.hostToken) {
        shown.reloaded = 'placements';
        shown.rebaked = affected;
        if (await shown.host.reload(shown.hostToken) === 'document-switched') {
          shown.reloaded = 'none';
          shown.rebaked = 0;
          shown.stale = affected;
          shown.switched = true;
          return;
        }
        await deps.whenSettled();
      } else {
        shown.stale = affected;
      }
    };

    let failure: string | null = null;
    try {
      await show();
      const missingAfter = deps.placementsMissing();
      // After a switch the count belongs to ANOTHER document — no proof either way.
      if (!shown.switched && missingAfter > missingBefore) {
        failure = `${missingAfter - missingBefore} placement(s) of the document could not be loaded after the push`;
      }
    } catch (e) {
      failure = `the reload failed: ${messageOf(e)}`;
    }

    try {
      if (failure === null) {
        try { deps.clearFailure(doc.id); } catch { /* cosmetic */ }
        // The rest of the post-save step (plan-777 F6): the thumbnail of the
        // replaced file — rendered from the reloaded document when it is the one
        // on screen, otherwise dropped, because a picture of the OLD bytes must
        // not stand next to the new ones (plan-776 F6) — then the rescan.
        try {
          await deps.finishSave?.(doc, shown.reloaded === 'open-document');
        } catch { /* the post-save step never fails a replace */ }
        return {
          ok: true,
          operationId,
          revision,
          reloaded: shown.reloaded,
          placementsRebaked: shown.rebaked,
          ...(shown.switched
            ? {
              reloadSkipped: 'document-switched' as const,
              detail: `"${doc.name || doc.path}" was written, but another document was opened while it was being `
                + 'replaced, so nothing was reloaded and that document was left as it is. Open the document to see it.',
            }
            : {}),
          ...(shown.stale > 0 ? { placementsStale: shown.stale } : {}),
          ...(shown.stale > 0 && !shown.switched
            ? {
              detail: `${shown.stale} placement(s) of this document sit in an open document with unsaved changes; `
                + 'they show the new geometry after that document is saved and reopened.',
            }
            : {}),
        };
      }

      // ── 8. restore ──
      if (!previous) {
        return fail('restore-failed', `${failure}; the previous file could not be read before the write, so `
          + 'nothing could be restored. The new file stays in place — check the project.', revision);
      }
      let restoredRevision: string;
      try {
        ({ revision: restoredRevision } = await backend.writeDocument(ref, previous.bytes, { expectedRevision: revision }));
      } catch (e) {
        return fail('restore-failed', `${failure}; restoring the previous file failed too: ${messageOf(e)}. `
          + 'The pushed file stays in place — check the project.', revision);
      }
      try {
        const before = missingBefore;
        await show();
        const after = deps.placementsMissing();
        if (after > before) throw new Error(`${after - before} placement(s) still missing after the restore`);
      } catch (e) {
        return fail('restore-failed', `${failure}; the previous file was written back but showing it failed: `
          + `${messageOf(e)}.`, restoredRevision);
      }
      return fail('reload-failed-restored', `${failure}. The previous file was restored and is shown again.`,
        restoredRevision);
    } finally {
      if (shown.host && shown.hostToken) shown.host.unlock(shown.hostToken);
    }
  } finally {
    if (open && token) open.unlock(token);
  }
}

// ─── GLB validation ─────────────────────────────────────────────────────

/** How long a full parse may take before the push is refused as unloadable. */
export const VALIDATE_TIMEOUT_MS = 120_000;

/** What the full parse needs of a loader — `GLTFLoader` (with its Draco loader) in production. */
export type ParseLoader = GlbParseLoader<{ scene: { traverse(fn: (o: unknown) => void): void } }>;

let _validationSeq = 0;

/**
 * Parse GLB bytes COMPLETELY in memory with the viewer's own loader — Draco
 * decode, every accessor, every texture — and throw on anything it could not
 * load. Nothing is added to a scene; the result is disposed at once.
 *
 * Goes through THE parse wrapper (`parseGlbCollectingResources`, plan-498)
 * like every other GLB load. The wrapper's one side effect — the file's
 * embedded FMU payloads put into the session's `binaryResources` — is held
 * under a throwaway document id and released again here, so a validation
 * leaves the store as it found it. The parse itself is the same loader call
 * on the same bytes: what passes and what is refused does not change.
 */
export async function validateGlbBytes(
  bytes: Uint8Array,
  loader?: ParseLoader,
  timeoutMs = VALIDATE_TIMEOUT_MS,
): Promise<void> {
  if (bytes.byteLength < 20) throw new Error('too short for a GLB');
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  if (view.getUint32(0, true) !== 0x46546c67) throw new Error('no glTF binary magic');
  if (view.getUint32(4, true) !== 2) throw new Error(`unsupported glTF version ${view.getUint32(4, true)}`);
  const parser: ParseLoader = loader
    ?? (await import('../../core/engine/rv-glb-parse')).gltfLoader as unknown as ParseLoader;
  const { binaryResources, parseGlbCollectingResources } = await import('../../core/engine/rv-binary-resources');
  const copy = bytes.slice().buffer as ArrayBuffer;
  const validationId = `replace-validation:${++_validationSeq}`;
  let timer: ReturnType<typeof setTimeout> | null = null;
  const timeout = new Promise<never>((_, reject) => {
    timer = setTimeout(() => reject(new Error(`parse did not finish within ${timeoutMs / 1000} s`)), timeoutMs);
  });
  try {
    const gltf = await Promise.race([parseGlbCollectingResources(copy, validationId, parser), timeout]);
    disposeParsed(gltf.scene);
  } finally {
    if (timer) clearTimeout(timer);
    // The collection runs synchronously before the parse starts, so this also
    // holds when the parse budget ran out and the loader is still working.
    binaryResources.releaseDocument(validationId);
  }
}

function disposeParsed(root: { traverse(fn: (o: unknown) => void): void }): void {
  root.traverse((o) => {
    const mesh = o as {
      geometry?: { dispose?: () => void };
      material?: unknown;
    };
    mesh.geometry?.dispose?.();
    const materials = Array.isArray(mesh.material) ? mesh.material : mesh.material ? [mesh.material] : [];
    for (const m of materials as Array<Record<string, unknown> & { dispose?: () => void }>) {
      for (const value of Object.values(m)) {
        const tex = value as { isTexture?: boolean; dispose?: () => void } | null;
        if (tex && typeof tex === 'object' && tex.isTexture) tex.dispose?.();
      }
      m.dispose?.();
    }
  });
}

