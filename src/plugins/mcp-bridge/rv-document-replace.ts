/** The real viewer, project store and scene store behind {@link ReplaceDeps}. */
export async function createViewerReplaceDeps(
  viewer: unknown,
  sessionId: string,
  opts: {
    /** Test seam — the scene store to act on (default: the app singleton). */
    sceneStore?: () => import('../../core/hmi/scene/scene-store').SceneStore | null;
    /** Test seam — the staging fetch (default: same-origin `fetch`). */
    fetchStaged?: (url: string) => Promise<Uint8Array>;
    /** Test seam — the full-parse budget (default {@link VALIDATE_TIMEOUT_MS}). */
    validateTimeoutMs?: number;
    /** Test seam — the loader of the full parse (default: the viewer's shared `gltfLoader`). */
    validateLoader?: ParseLoader;
  } = {},
): Promise<ReplaceDeps> {
  const [{ getProjectStore }, documents, singleton, assets, problems] = await Promise.all([
    import('../../core/project/project-store'),
    import('../../core/project/rv-project-documents'),
    import('../../core/hmi/scene/scene-store-singleton'),
    import('../../core/editor/active-asset-store'),
    import('../../core/hmi/problems-store'),
  ]);
  const getSceneStore = opts.sceneStore ?? singleton.getSceneStore;
  const v = viewer as {
    modes?: { activeMode?: string };
    emit?: (event: string, data: unknown) => void;
    whenSceneReady?: () => Promise<void>;
    placements?: PlacementHost['placements'] & {
      progress?: { missing: number };
      whenMaterialized?: () => Promise<void>;
    };
    bakeRegistry?: PlacementHost['bakeRegistry'];
  } | null | undefined;

  const handleFor = (): ReplaceDocumentHandle | null => {
    const store = getSceneStore();
    if (!store || !store.openDocumentId) return null;
    return {
      // `dirty`, not `hasUnpersistedWork()`: right after a save the draft timer is
      // still armed, but only to drop the draft of a clean document.
      isDirty: () => store.document.dirty,
      lock: () => store.tryLockForReplace(),
      unlock: (t) => store.unlockReplace(t),
      reload: (t) => store.reloadOpenDocumentForReplace(t),
    };
  };

  return {
    sessionId: () => sessionId,
    activeProjectId: () => getProjectStore().getProject()?.id ?? null,
    backend: () => getProjectStore().getBackend(),
    findDocument: (id) => {
      const row = documents.documentsOf(getProjectStore().getProject()).find((d) => d.id === id);
      return row ? { id: row.id, path: row.path, name: row.name ?? '' } : null;
    },
    pageOrigin: () => (typeof location !== 'undefined' ? location.origin : 'null'),
    fetchStaged: opts.fetchStaged ?? (async (url) => {
      const response = await fetch(url, { credentials: 'same-origin', cache: 'no-store' });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      return new Uint8Array(await response.arrayBuffer());
    }),
    validateGlb: (bytes) => validateGlbBytes(bytes, opts.validateLoader, opts.validateTimeoutMs),
    hasDraft: async (id) => {
      const store = getSceneStore();
      return store ? store.hasDocumentDraft(id) : false;
    },
    editorHolds: (id) => {
      if (v?.modes?.activeMode !== 'editor') return false;
      const ctx = assets.getActiveAssetContext();
      if (!id) return !!ctx;
      const base = ctx?.doc.base as { kind?: string; documentId?: string } | undefined;
      return getSceneStore()?.openDocumentId === id || (base?.kind === 'document' && base.documentId === id);
    },
    openTarget: (id) => (getSceneStore()?.openDocumentId === id ? handleFor() : null),
    openHost: () => handleFor(),
    invalidate: async (doc) => {
      // The planner's own invalidation (registry keys) hangs on this
      // event — a replace IS a document save from the project's point of view.
      // Announced EARLY, before the reload (plan-777 P8); `finishSave` below
      // runs the rest of the post-save step without a second announce.
      announceDocumentSaved(v as FinishSaveViewer | null | undefined, { documentId: doc.id, relPath: doc.path });
      if (!v?.placements || !v.bakeRegistry) return 0;
      return invalidateDocumentPlacements({ placements: v.placements, bakeRegistry: v.bakeRegistry }, doc);
    },
    placementsMissing: () => v?.placements?.progress?.missing ?? 0,
    whenSettled: async () => {
      await v?.whenSceneReady?.();
      await v?.placements?.whenMaterialized?.();
    },
    reportFailure: (doc, result) => {
      problems.reportProblem({
        id: `${REPLACE_PROBLEM_CODE}:${doc.id}`,
        severity: result.reason === 'restore-failed' ? 'error' : 'warning',
        code: REPLACE_PROBLEM_CODE,
        title: `Document replace refused: ${doc.name} (${result.reason})`,
        detail: result.detail,
      });
    },
    clearFailure: (id) => problems.clearProblem(`${REPLACE_PROBLEM_CODE}:${id}`),
    finishSave: async (doc, loaded) => {
      const store = getProjectStore();
      await finishDocumentSave({
        // Null-safe: no viewer means no render (and no pointer change); the
        // drop of a not-loaded document and the rescan still run.
        viewer: (viewer ?? null) as FinishSaveViewer | null,
        store,
        backend: store.getBackend(),
        documentId: doc.id,
        relPath: doc.path,
        render: loaded,
        announce: false,
      });
    },
  };
}
