/**
 * rv-document-replace — replace ONE project document's file from outside and
 * make the viewer show it. Born on the abandoned Blender live link (plan-527,
 * commit 1776f3bd), ported as generic machinery for plan-764.
 *
 * The browser stays the only writer of the project: an outside producer stages
 * the new bytes same-origin (CONNECT), and the caller (an MCP tool) hands this
 * module the staging URL — or an in-page producer (the USD extras apply,
 * plan-764) hands it the bytes directly. The work runs in a FIXED order — every
 * step is only answerable once the one before it held:
 *
 *   1. `operationId` known → the SAME promise / the stored result (never a
 *      second write). The operation is registered as `pending` BEFORE the first
 *      `await`, so two calls with one id can never both run.
 *   2. project / document / staging origin → `project-mismatch`, `not-found`,
 *      `read-only`, `foreign-origin` (no fetch; no origin with in-page bytes).
 *   3. a draft of the target document — open or not → `local-changes`.
 *   4. the target is open: dirty → `local-changes`; else the scene's replace
 *      lock (every edit / undo / redo / save refused until step 8), dirty
 *      re-checked under the lock.
 *   5. fetch (staging URL only) + FULL parse with the viewer's own loader
 *      (Draco included), no scene → `invalid-glb`, nothing written.
 *   6. previous bytes kept; `writeDocument` with the expected revision
 *      (`'any'` overrides ONLY the revision conflict, never step 3/4).
 *   7. caches: `ModelCache.invalidate` for every placement source of the
 *      document (keys via `PlacementInstancer.sourceOf`), the GLB blob cache,
 *      `document-saved` for the planner; the open document is reloaded with
 *      the camera kept, else a clean open document hosting placements of it is.
 *      `document-saved` is announced HERE, early (`announceDocumentSaved`), so
 *      the planner drops its stale bytes before the reload; the rest of the
 *      post-save step (thumbnail, rescan) runs after the proof, step 8.
 *      LOP #180: the lock remembers WHICH document it was taken on. When another
 *      document was opened meanwhile, nothing is reloaded and that document's
 *      draft is left alone — the file IS written, and the result says
 *      `reloaded: 'none'`, `reloadSkipped: 'document-switched'`.
 *   8. success is PROVEN per operation: a reload that throws, or a rise of the
 *      placements' `missing` count, restores the previous bytes (precondition:
 *      the revision just written) → `reload-failed-restored`, or — when that
 *      fails as well — `restore-failed`. Never a claimed success.
 *
 * Every dependency on the running viewer goes through {@link ReplaceDeps}, so
 * the order above is testable without a browser project; the production deps
 * are {@link createViewerReplaceDeps}.
 *
 * Node-safe at module level (the MCP parity gate imports the tool classes in
 * Node): everything heavier is imported dynamically inside the functions.
 */

