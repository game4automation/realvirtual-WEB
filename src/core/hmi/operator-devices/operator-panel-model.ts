/**
 * Operator panel model (plan-542 F9) — the declarative description of a
 * station's operator panel, its validator and its evaluation. No React.
 *
 * An {@link OperatorPanelConfig} is PURE JSON DATA: no functions, no React
 * nodes, no imports. Colours are IEC token names (`"capColor": "blue"`),
 * icons are names from {@link STATUS_ICONS}, the layout is row / column
 * numbers on a grid of equal columns, and every condition is data:
 *
 *   { "signal": "i_SS_ESTOP1", "is": false }
 *   { "all": [ … ] }   { "any": [ … ] }   { "not": { … } }
 *
 * So a panel can be written by hand, generated by an AI, stored in a `.json`
 * file — and later carried inside a GLB — without a line of code. The generic
 * {@link OperatorPanel} renders any valid config; {@link validateOperatorPanelConfig}
 * says precisely what is wrong with an invalid one ("buttons[3].signal 'BT9'
 * not found in model").
 */

import { IEC_CAP, IEC_LAMP, type IecCapColor, type IecLampColor } from '../shared-sx';
import { createSignalWriter, type SignalStore, type SignalWriter } from '../../engine/rv-signal-store';
import { connectionModeLabel, type ConnectionModeState } from '../../engine/rv-connection-mode';

// ─── Config (JSON) ──────────────────────────────────────────────────────

/** A condition on boolean signals: equality, and its combinations. */
export type Condition =
  | { signal: string; is: boolean }
  | { all: Condition[] }
  | { any: Condition[] }
  | { not: Condition };

/** A lamp as wired: its output signal and colour. */
export interface PanelLampConfig {
  signal: string;
  color: IecLampColor;
  /** False when the simulation never writes this lamp — drawn "not driven" there. Default true. */
  simDriven?: boolean;
  /** Flash (2 Hz) while this holds, e.g. a fault that can be acknowledged. */
  flashWhen?: Condition;
}

/** A place on the panel grid (1-based). Devices sharing a cell stack in it. */
export interface PanelCell {
  row: number;
  col: number;
}

export interface PanelButtonConfig extends PanelCell {
  /** Accessible name, e.g. "Acknowledge". */
  label: string;
  /** Legend plate text; defaults to `label`. */
  legend?: string;
  /** The input it writes: true while held, false on release. */
  signal: string;
  capColor: IecCapColor;
  lamp?: PanelLampConfig;
  /** Draws a separator on the cell's left edge (e.g. an immediate stop). */
  separated?: boolean;
}

export interface PanelSelectorConfig extends PanelCell {
  label: string;
  /** Caption below the switch; defaults to `label`. */
  caption?: string;
  variant: 'knob' | 'key';
  /** The input it writes (latched). */
  signal: string;
  /** Left, then right position, each with the value it writes. */
  positions: [PanelPositionConfig, PanelPositionConfig];
  lamp?: PanelLampConfig;
}

export interface PanelPositionConfig {
  legend: string;
  value: boolean;
}

export interface PanelEstopConfig extends PanelCell {
  label: string;
  signal: string;
  /** Normally closed: pressed writes false. Default true. */
  normallyClosed?: boolean;
  lamp?: PanelLampConfig;
}

export interface PanelTowerSegmentConfig {
  name: string;
  signal: string;
  color: IecLampColor;
  simDriven?: boolean;
}

/** A title-bar chip shown while its condition holds (e.g. HAND). */
export interface PanelChipConfig {
  /** Accessible name, e.g. "Operating mode: Hand". */
  label: string;
  text: string;
  when: Condition;
  tone?: 'warn' | 'neutral';
}

export const STATUS_TONES = ['ok', 'neutral', 'action', 'fault'] as const;
export type StatusTone = (typeof STATUS_TONES)[number];

export const STATUS_ICONS = ['check', 'hourglass', 'play', 'error', 'warning', 'info'] as const;
export type StatusIcon = (typeof STATUS_ICONS)[number];

/** One rule of the status strip; the first whose `when` holds wins, a rule without `when` always holds. */
export interface PanelStatusRule {
  /** Stable id of the state (`data-state`), e.g. "fault-estop". */
  kind: string;
  tone: StatusTone;
  /** Defaults by tone: ok check · neutral hourglass · action play · fault error. */
  icon?: StatusIcon;
  text: string;
  /** The restart step (1-based) this state is at; omit when no restart is due. */
  step?: number;
  when?: Condition;
}

export interface OperatorPanelConfig {
  /** Format version. */
  version: 1;
  /** Plugin id, window panelId and visibility id. */
  id: string;
  title: string;
  /** Window width in px. Default 300. */
  width?: number;
  position?: { x: number; y: number };
  /** Grid columns (equal widths). Default 3. */
  columns?: number;
  buttons: PanelButtonConfig[];
  selectors: PanelSelectorConfig[];
  estops: PanelEstopConfig[];
  /** Top to bottom, as the tower shows them. */
  stackLight: PanelTowerSegmentConfig[];
  chips?: PanelChipConfig[];
  status: PanelStatusRule[];
  /** The restart sequence the status steps refer to. */
  restart?: { hint: string; steps: string[] };
  /** Which E-stop stays in the title bar when the window is collapsed. Default 0. */
  headerEstop?: number;
}

// ─── Evaluation ─────────────────────────────────────────────────────────

/** Reads a boolean signal. */
export type SignalReader = (name: string) => boolean;

export function evaluateCondition(c: Condition, v: SignalReader): boolean {
  if ('signal' in c) return v(c.signal) === c.is;
  if ('all' in c) return c.all.every((x) => evaluateCondition(x, v));
  if ('any' in c) return c.any.some((x) => evaluateCondition(x, v));
  return !evaluateCondition(c.not, v);
}

/** The status-strip state for the current signals: the first rule that holds. */
export function resolveStatus(config: OperatorPanelConfig, v: SignalReader): PanelStatusRule | null {
  return config.status.find((r) => !r.when || evaluateCondition(r.when, v)) ?? null;
}

function conditionSignals(c: Condition, out: Set<string>): void {
  if ('signal' in c) out.add(c.signal);
  else if ('all' in c) c.all.forEach((x) => conditionSignals(x, out));
  else if ('any' in c) c.any.forEach((x) => conditionSignals(x, out));
  else conditionSignals(c.not, out);
}

/** Every signal the panel reads or writes, each once. */
export function operatorPanelSignals(config: OperatorPanelConfig): string[] {
  const out = new Set<string>();
  const lamp = (l?: PanelLampConfig) => {
    if (!l) return;
    out.add(l.signal);
    if (l.flashWhen) conditionSignals(l.flashWhen, out);
  };
  for (const s of config.selectors) { out.add(s.signal); lamp(s.lamp); }
  for (const b of config.buttons) { out.add(b.signal); lamp(b.lamp); }
  for (const t of config.stackLight) out.add(t.signal);
  for (const e of config.estops) { out.add(e.signal); lamp(e.lamp); }
  for (const c of config.chips ?? []) conditionSignals(c.when, out);
  for (const r of config.status) if (r.when) conditionSignals(r.when, out);
  return [...out];
}

// ─── Validation ─────────────────────────────────────────────────────────

export interface OperatorPanelValidation {
  /** The config when its STRUCTURE is valid (it may still name signals the model lacks). */
  config: OperatorPanelConfig | null;
  /** Human-readable problems, each with its JSON path. Empty = valid. */
  errors: string[];
}

/**
 * One problem of a config with its JSON path (plan-555): `path` as segments
 * into the raw config (`['buttons', 0, 'signal']`, `[]` = the config itself),
 * `pathText` as the validator has always written it (`buttons[0].signal`;
 * top-level scalars as `config.id`). `${pathText} ${message}` is the string
 * of {@link OperatorPanelValidation.errors}.
 */
export interface OperatorPanelIssue {
  path: (string | number)[];
  pathText: string;
  message: string;
}

type Obj = Record<string, unknown>;
const isObj = (x: unknown): x is Obj => typeof x === 'object' && x !== null && !Array.isArray(x);

/** A JSON path as written text and as segments, built together. */
interface IssuePath { t: string; s: (string | number)[] }
const key = (p: IssuePath, k: string): IssuePath => ({ t: `${p.t}.${k}`, s: [...p.s, k] });
const index = (p: IssuePath, i: number): IssuePath => ({ t: `${p.t}[${i}]`, s: [...p.s, i] });
const top = (k: string): IssuePath => ({ t: k, s: [k] });
/** Top-level scalars are written `config.<key>`, their segments are just `[key]`. */
const CONFIG_ROOT: IssuePath = { t: 'config', s: [] };

/**
 * Checks a raw (parsed JSON) config. Structure first — types, colour names,
 * icon names, grid cells, conditions; then, when `hasSignal` is given, that
 * every signal the panel uses exists in the model.
 */
export function validateOperatorPanelConfig(raw: unknown, hasSignal?: (name: string) => boolean): OperatorPanelValidation {
  const { config, issues } = validateOperatorPanelConfigIssues(raw, hasSignal);
  return { config, errors: issues.map((i) => `${i.pathText} ${i.message}`) };
}

/**
 * {@link validateOperatorPanelConfig} with every problem as a structured
 * {@link OperatorPanelIssue} — the JSON editor puts each one at its text
 * range (plan-555). Same checks, same order, same messages.
 */
export function validateOperatorPanelConfigIssues(
  raw: unknown,
  hasSignal?: (name: string) => boolean,
): { config: OperatorPanelConfig | null; issues: OperatorPanelIssue[] } {
  const issues: OperatorPanelIssue[] = [];
  const err = (path: IssuePath, message: string) => issues.push({ path: path.s, pathText: path.t, message });
  if (!isObj(raw)) return { config: null, issues: [{ path: [], pathText: 'config', message: 'must be an object' }] };

  const str = (o: Obj, k: string, path: IssuePath, optional = false) => {
    if (o[k] === undefined && optional) return;
    if (typeof o[k] !== 'string' || (o[k] as string).length === 0) err(key(path, k), 'must be a non-empty string');
  };
  const oneOf = (o: Obj, k: string, path: IssuePath, allowed: readonly string[], optional = false) => {
    if (o[k] === undefined && optional) return;
    if (!allowed.includes(o[k] as string)) err(key(path, k), `must be one of ${allowed.join(', ')} (got ${JSON.stringify(o[k])})`);
  };
  const columns = typeof raw.columns === 'number' ? raw.columns : 3;
  const cell = (o: Obj, path: IssuePath) => {
    for (const k of ['row', 'col']) {
      if (!Number.isInteger(o[k]) || (o[k] as number) < 1) err(key(path, k), 'must be an integer ≥ 1');
    }
    if (Number.isInteger(o.col) && (o.col as number) > columns) err(key(path, 'col'), `must be ≤ columns (${columns})`);
  };
  const condition = (c: unknown, path: IssuePath): void => {
    if (!isObj(c)) { err(path, 'must be a condition object'); return; }
    const keys = Object.keys(c);
    if ('signal' in c) {
      str(c, 'signal', path);
      if (typeof c.is !== 'boolean') err(key(path, 'is'), 'must be true or false');
    } else if (keys.length === 1 && (keys[0] === 'all' || keys[0] === 'any')) {
      const list = c[keys[0]];
      if (!Array.isArray(list) || list.length === 0) err(key(path, keys[0]), 'must be a non-empty array');
      else list.forEach((x, i) => condition(x, index(key(path, keys[0]), i)));
    } else if (keys.length === 1 && keys[0] === 'not') {
      condition(c.not, key(path, 'not'));
    } else {
      err(path, 'must be {signal,is}, {all:[…]}, {any:[…]} or {not:{…}}');
    }
  };
  const lamp = (l: unknown, path: IssuePath) => {
    if (l === undefined) return;
    if (!isObj(l)) { err(path, 'must be an object'); return; }
    str(l, 'signal', path);
    oneOf(l, 'color', path, Object.keys(IEC_LAMP));
    if (l.simDriven !== undefined && typeof l.simDriven !== 'boolean') err(key(path, 'simDriven'), 'must be true or false');
    if (l.flashWhen !== undefined) condition(l.flashWhen, key(path, 'flashWhen'));
  };
  const list = (k: string, each: (o: Obj, path: IssuePath) => void, optional = false) => {
    const v = raw[k];
    if (v === undefined && optional) return;
    if (!Array.isArray(v)) { err(top(k), 'must be an array'); return; }
    v.forEach((o, i) => {
      const path = index(top(k), i);
      if (!isObj(o)) err(path, 'must be an object');
      else each(o, path);
    });
  };

  if (raw.version !== 1) err(top('version'), 'must be 1');
  str(raw, 'id', CONFIG_ROOT);
  str(raw, 'title', CONFIG_ROOT);
  list('buttons', (o, p) => {
    str(o, 'label', p); str(o, 'legend', p, true); str(o, 'signal', p);
    oneOf(o, 'capColor', p, Object.keys(IEC_CAP));
    lamp(o.lamp, key(p, 'lamp'));
    cell(o, p);
  });
  list('selectors', (o, p) => {
    str(o, 'label', p); str(o, 'caption', p, true); str(o, 'signal', p);
    oneOf(o, 'variant', p, ['knob', 'key']);
    const pos = o.positions;
    if (!Array.isArray(pos) || pos.length !== 2) err(key(p, 'positions'), 'must be exactly two positions');
    else pos.forEach((x, i) => {
      const pp = index(key(p, 'positions'), i);
      if (!isObj(x)) { err(pp, 'must be an object'); return; }
      str(x, 'legend', pp);
      if (typeof x.value !== 'boolean') err(key(pp, 'value'), 'must be true or false');
    });
    lamp(o.lamp, key(p, 'lamp'));
    cell(o, p);
  });
  list('estops', (o, p) => {
    str(o, 'label', p); str(o, 'signal', p);
    lamp(o.lamp, key(p, 'lamp'));
    cell(o, p);
  });
  list('stackLight', (o, p) => { str(o, 'name', p); str(o, 'signal', p); oneOf(o, 'color', p, Object.keys(IEC_LAMP)); });
  list('chips', (o, p) => { str(o, 'label', p); str(o, 'text', p); condition(o.when, key(p, 'when')); oneOf(o, 'tone', p, ['warn', 'neutral'], true); }, true);
  list('status', (o, p) => {
    str(o, 'kind', p); str(o, 'text', p);
    oneOf(o, 'tone', p, STATUS_TONES);
    oneOf(o, 'icon', p, STATUS_ICONS, true);
    if (o.when !== undefined) condition(o.when, key(p, 'when'));
    if (o.step !== undefined && (!Number.isInteger(o.step) || (o.step as number) < 1)) err(key(p, 'step'), 'must be an integer ≥ 1');
  });
  if (raw.restart !== undefined) {
    const r = raw.restart;
    if (!isObj(r)) err(top('restart'), 'must be an object');
    else {
      str(r, 'hint', top('restart'));
      if (!Array.isArray(r.steps) || r.steps.some((s) => typeof s !== 'string')) err(key(top('restart'), 'steps'), 'must be an array of strings');
    }
  }
  if (issues.length > 0) return { config: null, issues };

  const config = raw as unknown as OperatorPanelConfig;
  if (hasSignal) {
    const where = new Map<string, IssuePath>();
    const note = (signal: string, path: IssuePath) => { if (!where.has(signal)) where.set(signal, path); };
    const condPaths = (c: Condition, p: IssuePath): void => {
      if ('signal' in c) note(c.signal, key(p, 'signal'));
      else if ('all' in c) c.all.forEach((x, i) => condPaths(x, index(key(p, 'all'), i)));
      else if ('any' in c) c.any.forEach((x, i) => condPaths(x, index(key(p, 'any'), i)));
      else condPaths(c.not, key(p, 'not'));
    };
    const lampPaths = (l: PanelLampConfig | undefined, p: IssuePath) => {
      if (!l) return;
      note(l.signal, key(key(p, 'lamp'), 'signal'));
      if (l.flashWhen) condPaths(l.flashWhen, key(key(p, 'lamp'), 'flashWhen'));
    };
    const item = (k: string, i: number) => index(top(k), i);
    config.selectors.forEach((s, i) => { note(s.signal, key(item('selectors', i), 'signal')); lampPaths(s.lamp, item('selectors', i)); });
    config.buttons.forEach((b, i) => { note(b.signal, key(item('buttons', i), 'signal')); lampPaths(b.lamp, item('buttons', i)); });
    config.estops.forEach((e, i) => { note(e.signal, key(item('estops', i), 'signal')); lampPaths(e.lamp, item('estops', i)); });
    config.stackLight.forEach((t, i) => note(t.signal, key(item('stackLight', i), 'signal')));
    (config.chips ?? []).forEach((c, i) => condPaths(c.when, key(item('chips', i), 'when')));
    config.status.forEach((r, i) => { if (r.when) condPaths(r.when, key(item('status', i), 'when')); });
    for (const [signal, path] of where) {
      if (!hasSignal(signal)) err(path, `'${signal}' not found in model`);
    }
  }
  return { config, issues };
}

// ─── Controller (signal store ↔ snapshot) ──────────────────────────────

/** What a window renders: the panel's live state. */
export interface OperatorPanelSnapshot {
  /** False until the model carries every signal of the panel; the controls render disabled. */
  ready: boolean;
  values: Readonly<Record<string, boolean>>;
  /** The Simulation / PLC label. */
  modeLabel: string;
  /** True while the simulation drives the outputs (no interface has taken over). */
  simulated: boolean;
  /** Validation errors (JSON, structure, or signals the model lacks). */
  errors: readonly string[];
}

/** The read side a window needs; {@link OperatorPanelController} provides it. */
export interface OperatorPanelSource {
  readonly config: OperatorPanelConfig | null;
  subscribe(listener: () => void): () => void;
  getSnapshot(): OperatorPanelSnapshot;
  write(signal: string, value: boolean): void;
}

/** What the controller needs from a viewer: the signal store and the Simulation / PLC mode. */
export interface OperatorPanelHostViewer {
  readonly signalStore?: SignalStore | null;
  readonly connectionMode?: {
    readonly state: Pick<ConnectionModeState, 'mode' | 'source'> & Partial<Pick<ConnectionModeState, 'interfaceConnected'>>;
    subscribe(cb: () => void): () => void;
  } | null;
}

export const OFFLINE_SNAPSHOT: OperatorPanelSnapshot = { ready: false, values: {}, modeLabel: '', simulated: true, errors: [] };

/**
 * One operator panel's runtime, React-free: validates the config, subscribes
 * to its signals, publishes a snapshot and writes operator inputs with the
 * `hmi` writer kind. Used by the `OperatorPanelPlugin` (a plugin per config)
 * and by the `WebOperatorPanel` host (one per component in the model).
 */
export class OperatorPanelController implements OperatorPanelSource {
  readonly id: string;
  /** The validated config, or null when its JSON or structure is invalid. */
  readonly config: OperatorPanelConfig | null;
  private readonly _structureErrors: string[];
  private readonly _signals: string[];
  private _writer: SignalWriter | null = null;
  private _viewer: OperatorPanelHostViewer | null = null;
  private _cleanups: (() => void)[] = [];
  private readonly _listeners = new Set<() => void>();
  private _snapshot: OperatorPanelSnapshot;

  /**
   * `raw` is the parsed JSON. `opts.errors` replaces the structure check when
   * the caller already knows the config is unusable (e.g. it is not JSON).
   */
  constructor(raw: unknown, opts: { id?: string; errors?: readonly string[] } = {}) {
    const checked: OperatorPanelValidation = opts.errors && opts.errors.length > 0
      ? { config: null, errors: [...opts.errors] }
      : validateOperatorPanelConfig(raw);
    this.config = checked.config;
    this._structureErrors = checked.errors;
    const rawId = isObj(raw) && typeof raw.id === 'string' && raw.id ? raw.id : null;
    this.id = opts.id ?? checked.config?.id ?? rawId ?? 'operator-panel';
    this._signals = checked.config ? operatorPanelSignals(checked.config) : [];
    this._snapshot = { ...OFFLINE_SNAPSHOT, errors: checked.errors };
  }

  /** Every signal the panel reads or writes. */
  get signalNames(): readonly string[] { return this._signals; }

  /** True between {@link start} and {@link stop}. */
  get started(): boolean { return this._viewer !== null; }

  subscribe = (listener: () => void): (() => void) => {
    this._listeners.add(listener);
    return () => { this._listeners.delete(listener); };
  };

  getSnapshot = (): OperatorPanelSnapshot => this._snapshot;

  /** Writes an operator input. Ignored while the panel is not ready. */
  write(signal: string, value: boolean): void {
    if (!this._snapshot.ready || !this._writer) return;
    this._writer.set(signal, value);
  }

  /**
   * Connects to the viewer's signals. A config naming signals the model lacks
   * stays disabled and says which (with the JSON path).
   */
  start(viewer: OperatorPanelHostViewer): void {
    this.stop();
    const store = viewer.signalStore;
    if (!store || !this.config) return;
    this._viewer = viewer;
    const { errors } = validateOperatorPanelConfig(this.config, (name) => store.get(name) !== undefined);
    if (errors.length > 0) {
      console.warn(`[${this.id}] ${errors.join('; ')} — the operator panel stays disabled.`);
      this._publish({ ...OFFLINE_SNAPSHOT, errors });
      return;
    }
    // Operator kind, like the scene buttons a panel replaces: the PLC side
    // (virtual or real) reads these inputs exactly as it read a 3D panel.
    this._writer = createSignalWriter(store, `hmi:${this.id}`, 'hmi');
    const sync = () => this._sync();
    for (const name of this._signals) this._cleanups.push(store.subscribe(name, sync));
    const mode = viewer.connectionMode;
    if (mode) this._cleanups.push(mode.subscribe(sync));
    this._sync();
  }

  /** Disconnects; the window shows the panel disabled (or its config errors). */
  stop(): void {
    for (const fn of this._cleanups) fn();
    this._cleanups = [];
    const wasStarted = this._viewer !== null;
    this._viewer = null;
    this._writer = null;
    if (wasStarted) this._publish({ ...OFFLINE_SNAPSHOT, errors: this._structureErrors });
  }

  private _sync(): void {
    const store = this._viewer?.signalStore;
    if (!store) return;
    const values: Record<string, boolean> = {};
    let changed = !this._snapshot.ready;
    for (const name of this._signals) {
      values[name] = store.getBool(name);
      if (values[name] !== this._snapshot.values[name]) changed = true;
    }
    const mode = this._viewer?.connectionMode;
    const modeLabel = mode ? connectionModeLabel(mode.state) : '';
    const simulated = mode ? mode.state.mode === 'Simulation' && mode.state.source !== 'interface' : true;
    if (!changed && modeLabel === this._snapshot.modeLabel && simulated === this._snapshot.simulated) return;
    this._publish({ ready: true, values, modeLabel, simulated, errors: [] });
  }

  private _publish(next: OperatorPanelSnapshot): void {
    this._snapshot = next;
    for (const listener of this._listeners) listener();
  }
}
