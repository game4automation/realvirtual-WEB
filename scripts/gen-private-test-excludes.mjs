/**
 * gen-private-test-excludes.mjs — maintain the list of PRIVATE-DEPENDENT test files.
 *
 * A test is private-dependent when it imports (statically or dynamically) a module
 * that only exists with the private sibling repos present: `@rv-private/*`,
 * `@rv-projects/*`, or a relative path into `realvirtual-WebViewer-Private~`,
 * `realvirtual-web-pro` or `realvirtual-Connect~`. In the COMMUNITY edition (the
 * public GitHub mirror, no private folders) those imports can never resolve, so:
 *
 *   - `tsconfig.json` excludes these files between the marker comments below —
 *     plain `npx tsc --noEmit` therefore shows the COMMUNITY view everywhere.
 *     The full dev/CI typecheck runs `npm run typecheck` (tsconfig.full.json,
 *     empty exclude), which requires the private folder.
 *   - `tests/private-dependent-tests.json` feeds the vitest configs, which skip
 *     these files when the private folder is absent.
 *
 * The list is GENERATED — never edit it by hand. Run `node scripts/gen-private-test-excludes.mjs`
 * after adding or removing a private import in a test; the guard test
 * `tests/private-test-excludes.node.test.ts` fails when the list drifts.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const LIST_PATH = join(ROOT, 'tests', 'private-dependent-tests.json');
const TSCONFIG_PATH = join(ROOT, 'tsconfig.json');
// Sentinels are STRING entries, not comments: several scripts read tsconfig.json
// with strict JSON.parse (scripts/_rv-fs-utils.mjs readJson, the embed staging),
// and a JSONC comment there breaks them. As exclude patterns these two strings
// match no file, so they are inert.
const BEGIN = '__RV-PRIVATE-TEST-EXCLUDES-BEGIN__ (generated by scripts/gen-private-test-excludes.mjs — do not edit)';
const END = '__RV-PRIVATE-TEST-EXCLUDES-END__';

/** Import specifiers that need a private sibling repo to resolve. */
export function isPrivateSpecifier(spec) {
  if (spec.startsWith('@rv-private/') || spec.startsWith('@rv-projects/')) return true;
  return /(^|\/)(realvirtual-WebViewer-Private~|realvirtual-web-pro|realvirtual-Connect~)(\/|$)/.test(spec);
}

/** All import/require specifiers of one source file (static, dynamic, mock targets). */
function importSpecifiers(source) {
  const specs = [];
  const re = /(?:\bfrom\s*|\bimport\s*\(\s*|\brequire\s*\(\s*|\bimport\s+)['"]([^'"]+)['"]/g;
  for (let m; (m = re.exec(source)) !== null;) specs.push(m[1]);
  return specs;
}

/**
 * True when the file reaches into a private sibling by PATH rather than by import
 * — `readFileSync('../realvirtual-WebViewer-Private~/tier-manifest.json')`, a
 * `privateRoot:` option, and so on. Import scanning alone missed these, and they
 * fail just as hard in a community clone (ENOENT instead of a resolve error).
 */
function referencesPrivatePath(source) {
  return /realvirtual-WebViewer-Private~|realvirtual-web-pro|realvirtual-Connect~/.test(source);
}

/** Opt-in marker for a test that needs the private sibling in a way no scan can see. */
function hasRequiresPrivateMarker(source) {
  return /@rv-requires-private\b/.test(source);
}

/** Recursively collect test files under tests/. */
function collectTestFiles(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) collectTestFiles(path, out);
    else if (/\.(test|spec)\.(ts|tsx)$/.test(entry.name)) out.push(path);
  }
  return out;
}

/** Compute the sorted repo-relative list of private-dependent test files. */
export function computePrivateDependentTests(root = ROOT) {
  const files = collectTestFiles(join(root, 'tests'));
  const result = [];
  for (const abs of files) {
    const source = readFileSync(abs, 'utf8');
    const needsPrivate = importSpecifiers(source).some(isPrivateSpecifier)
      || referencesPrivatePath(source)
      || hasRequiresPrivateMarker(source);
    if (needsPrivate) result.push(relative(root, abs).replace(/\\/g, '/'));
  }
  return result.sort();
}

/** Rewrite the exclude block in tsconfig.json. Output stays strict JSON (see BEGIN). */
function writeTsconfigExcludes(list) {
  const raw = readFileSync(TSCONFIG_PATH, 'utf8');
  const entries = [BEGIN, ...list, END].map((f) => `    ${JSON.stringify(f)}`).join(',\n');
  const block = `  "exclude": [\n${entries}\n  ]`;
  let next;
  if (raw.includes(BEGIN)) {
    next = raw.replace(/[ \t]*"exclude":\s*\[[\s\S]*?__RV-PRIVATE-TEST-EXCLUDES-END__"\s*\]/, block);
  } else {
    // Insert as the last top-level key, before the file's closing brace.
    next = raw.replace(/\r?\n\}\s*$/, `,\n${block}\n}\n`);
  }
  if (!next.includes(BEGIN)) {
    throw new Error('tsconfig.json rewrite failed — marker block was not inserted.');
  }
  JSON.parse(next); // tsconfig.json must stay strict JSON — other tooling parses it that way.
  writeFileSync(TSCONFIG_PATH, next);
}

const isMain = process.argv[1] && fileURLToPath(new URL(import.meta.url)).endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop());
if (isMain) {
  const list = computePrivateDependentTests();
  writeFileSync(LIST_PATH, `${JSON.stringify(list, null, 2)}\n`);
  writeTsconfigExcludes(list);
  console.log(`${list.length} private-dependent test files → tests/private-dependent-tests.json + tsconfig.json exclude`);
}
