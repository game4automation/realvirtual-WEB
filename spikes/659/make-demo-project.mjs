// plan-659 Phase 2b — build the demo PROJECT that the real viewer opens.
//
// Since plan-735 a GLB dropped into `public/models/` is invisible: a document
// exists only when a `project.json` declares it in `documents[]`. So the demo
// is a project folder of its own — the same artefact shape a delivered project
// has — served from the dev root and opened with
// `?projectUrl=/spike-659-duck/&doc=<id>`.
//
// Own folder, not a row in `demo-realvirtual/`: that project is a DELIVERED
// artefact (five carriers, byte-identical), and a spike does not belong in it
// until someone decides to deliver it.
//
// Since plan-659 stage 2 the LICENCE reason for keeping it out is gone: the
// collision hulls are no longer CC BY-NC-SA meshes but original primitives
// (`duck/build-collision-primitives.mjs`), so nothing this project loads is
// NonCommercial. What remains is Apache-2.0 - the policies and every number
// taken from the MJCF - which needs the attribution and the licence text of
// `fixtures/microduck/NOTICE.md` carried along, plus its trademark rules.
//
//   node spikes/659/duck/build-collision-primitives.mjs   # the simulated hulls
//   node spikes/659/duck/build-duck.mjs      # the robot (with its Drives)
//   node spikes/659/make-demo-project.mjs    # this file
//   -> http://localhost:5659/?projectUrl=/spike-659-duck/&doc=doc_rv_walker_659
import { existsSync, mkdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { ensureSpikeDeps } from './ensure-deps.mjs';

ensureSpikeDeps();

const here = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(here, 'duck/rv-duck.glb');
const OUT_DIR = resolve(here, '../../public/spike-659-duck');
const GLB_NAME = 'rv-walker.glb';
const DOC_ID = 'doc_rv_walker_659';
/** The operator panel of this robot — the SSOT, in the private tree. */
const PANEL_JSON = resolve(here, '../../../realvirtual-WebViewer-Private~/src/mujoco/robot-panel.json');

mkdirSync(OUT_DIR, { recursive: true });

// ── The operator panel goes INTO the document ────────────────────────────
//
// `robot-panel.json` is a plan-542 `OperatorPanelConfig`; carried as the
// `Config` field of a `WebOperatorPanel` component it is exactly what the
// Laser Welding Assembly Station does. The viewer's own host then builds the
// controller and draws the window — no plugin that knows this particular
// robot, no rebuild for a panel change, and the panel is editable in the
// inspector's JSON editor like a customer's would be.
//
// It lands on a node of its own ("OperatorPanel") rather than on the asset
// root: a component CLAIMS its node, so the empty node survives the
// destructive bake and the panel is a visible, selectable thing in the
// hierarchy — which is the point being demonstrated.
if (!existsSync(PANEL_JSON)) {
  throw new Error(`operator panel config missing: ${PANEL_JSON} (private tree not checked out?)`);
}
const panelConfig = JSON.parse(readFileSync(PANEL_JSON, 'utf8'));

const io = new NodeIO();
const doc = await io.read(SRC);
const glbRoot = doc.getRoot();
const scene = glbRoot.getDefaultScene() ?? glbRoot.listScenes()[0];
const assetRoot = scene.listChildren()[0];
if (!assetRoot) throw new Error('rv-duck.glb has no root node');
assetRoot.addChild(doc.createNode('OperatorPanel').setExtras({
  realvirtual: {
    WebOperatorPanel: {
      Title: 'Robot',
      // A JSON STRING: that is the authored form of the field (the reader
      // tolerates an object, but the inspector and MCP both write a string,
      // and the demo should carry what an author would produce).
      Config: JSON.stringify(panelConfig),
      Dock: 'top-left',
      StartCollapsed: false,
    },
  },
}));
await io.write(resolve(OUT_DIR, GLB_NAME), doc);

const bytes = readFileSync(resolve(OUT_DIR, GLB_NAME));
const stat = statSync(resolve(OUT_DIR, GLB_NAME));

// The artefacts are generated, so they are not versioned — the generators are.
writeFileSync(resolve(OUT_DIR, '.gitignore'), [
  '# plan-659: generated by spikes/659/make-demo-project.mjs. Regenerate, never commit',
  '# (this repo mirrors to a public remote, and the GLB is a build artefact).',
  '*.glb',
  'project.json',
  '',
].join('\n'));

const project = {
  schemaVersion: 2,
  id: 'prj_spike659',
  name: 'MuJoCo Walker (Spike 659)',
  canonicalName: 'spike659',
  kind: 'demo',
  createdAt: '2026-10-22',
  activeSceneId: null,
  settings: { defaultModel: GLB_NAME },
  documents: [
    {
      id: DOC_ID,
      name: 'MuJoCo Walker',
      path: GLB_NAME,
      mode: 'hmi',
      sizeBytes: stat.size,
      mtimeMs: stat.mtimeMs,
      sha256: createHash('sha256').update(bytes).digest('hex'),
      documentInfo: {
        v: 1,
        summary: 'A two-legged service robot walking in realvirtual WEB, driven by a '
          + 'MuJoCo physics world and an ONNX locomotion policy at 50 Hz.',
        description: '# MuJoCo Walker (plan-659 spike)\n\n'
          + 'A small two-legged service robot that **walks**: gravity, ground contact and '
          + 'position actuators are simulated in MuJoCo (WASM), a trained ONNX policy sets '
          + 'the 14 joint targets 50 times a second, and the resulting joint angles arrive '
          + 'in the scene through the robot’s own **Drives** — the same components a '
          + 'conveyor or a robot axis uses.\n\n'
          + '## Try this\n\n'
          + '- The panel at the bottom left starts and stops the robot, sets the forward '
          + 'speed `vx` and resets it to the start pose. Its legend card lists the keys '
          + 'that steer it — hold them, and they mean directions on screen.\n'
          + '- Open the hierarchy: all 14 joints are ordinary nodes with a Drive, so they '
          + 'can be selected, hidden and inspected while the robot walks.\n\n'
          + '**Internal spike.** Both halves of the geometry are realvirtual’s own work, '
          + 'built from primitives: the visible robot, and since plan-659 stage 2 the '
          + 'eleven collision hulls the physics actually runs on. Nothing here loads a '
          + 'CC BY-NC-SA file. The kinematics, the masses and inertias and the two '
          + 'trained policies are Apache-2.0 — robot model and locomotion policies: '
          + 'Microduck by Pollen Robotics, see the fixture NOTICE.',
        updatedAt: new Date().toISOString(),
        updatedBy: 'realvirtual',
      },
    },
  ],
};
writeFileSync(resolve(OUT_DIR, 'project.json'), JSON.stringify(project, null, 2) + '\n');

console.log(`demo project written: ${OUT_DIR}`);
console.log(`  ${GLB_NAME}  ${(stat.size / 1024).toFixed(0)} KB`);
console.log(`  open: http://localhost:5659/?projectUrl=/spike-659-duck/&doc=${DOC_ID}`);
